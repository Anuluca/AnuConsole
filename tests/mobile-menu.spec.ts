import { test, expect } from "@playwright/test";

test("手机全屏菜单、路由选择、焦点及页脚主题", async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== "mobile", "仅适用于手机布局");
  await page.goto("/");
  const trigger = page.getByRole("button", { name: "打开菜单", exact: true });
  await expect(page.locator(".topbar .logout")).toHaveCount(0);
  await expect(trigger).toBeVisible();
  await expect(page.locator(".sidebar")).toBeHidden();
  await expect(page.locator(".topbar .theme-switch")).toHaveCount(0);
  const theme = page.locator(".console-footer").getByRole("button", { name: "显示主题", exact: true });
  await expect(theme).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
  await expect(theme).toHaveCSS("border-top-width", "0px");
  await expect(page.locator(".console-footer")).toHaveCSS("font-size", "9px");
  await expect(page.locator(".console-footer")).toHaveCSS("padding-top", "9.5px");
  const copyright = await page.locator(".console-footer > span").boundingBox();
  const themeBox = await theme.boundingBox();
  expect(themeBox!.x).toBeLessThan(copyright!.x);
  await theme.click();
  const options = page.getByRole("listbox", { name: "主题选项" });
  await expect(options).toBeInViewport();
  expect((await options.boundingBox())!.y + (await options.boundingBox())!.height).toBeLessThanOrEqual(themeBox!.y);
  await page.getByRole("option", { name: "浅色", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
  const initial = await page.locator(".main-content").boundingBox();
  await trigger.click();
  const menu = page.getByRole("dialog", { name: "菜单", exact: true });
  await expect(menu).toBeVisible();
  await expect(menu.getByRole("button", { name: "关闭菜单", exact: true })).not.toBeFocused();
  await expect(menu).not.toBeFocused();
  await expect(menu.getByRole("heading", { name: "菜单", exact: true })).not.toBeFocused();
  await page.keyboard.press("Tab");
  expect(await menu.evaluate(element => element.contains(document.activeElement))).toBe(true);
  const logout = menu.getByRole("button", { name: "退出", exact: true });
  await expect(logout).toBeInViewport();
  const footer = await page.locator(".mobile-menu-footer").boundingBox();
  const logoutBounds = await logout.boundingBox();
  expect(Math.abs(footer!.x + footer!.width - logoutBounds!.x - logoutBounds!.width)).toBeLessThanOrEqual(1);
  expect(Math.abs(footer!.y + footer!.height - page.viewportSize()!.height + 24)).toBeLessThanOrEqual(1);
  await logout.click();
  await expect(page.getByRole("alertdialog")).toBeVisible();
  await expect(page.locator("body")).toBeFocused();
  await page.getByRole("button", { name: "取消", exact: true }).click();
  await expect(page.getByRole("alertdialog")).toBeHidden();
  await expect(menu).toBeVisible();
  const bounds = await menu.boundingBox();
  expect(bounds!.x).toBe(0); expect(bounds!.y).toBe(0);
  expect(bounds!.width).toBe(page.viewportSize()!.width);
  expect(bounds!.height).toBe(page.viewportSize()!.height);
  await page.screenshot({ path: testInfo.outputPath("mobile-menu.png") });
  await page.keyboard.press("Escape");
  await expect(menu).toBeHidden();
  await expect(trigger).not.toBeFocused();
  const after = await page.locator(".main-content").boundingBox();
  expect(Math.abs(after!.x - initial!.x)).toBeLessThanOrEqual(1);
  expect(Math.abs(after!.y - initial!.y)).toBeLessThanOrEqual(1);
  await trigger.click();
  await menu.getByRole("link", { name: "浏览量", exact: true }).click();
  await expect(page).toHaveURL("/anutrium/monitor/ga4");
  await expect(menu).toBeHidden();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("浏览量");
  await trigger.click();
  await page.getByRole("button", { name: "关闭菜单", exact: true }).click();
  await expect(menu).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  expect(await page.locator("body").evaluate(el => el.style.overflow)).toBe("");
});
